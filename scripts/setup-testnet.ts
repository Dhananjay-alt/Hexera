/**
 * One-shot Hedera testnet setup for Hexera. Needs a funded testnet account
 * (portal.hedera.com) in HEDERA_OPERATOR_ID / HEDERA_OPERATOR_KEY.
 *
 * Creates:
 *  - the deposit treasury: an account whose key is a 2-of-3 KeyList
 *  - a test stablecoin (6 decimals) unless HEXERA_TOKEN_ID is already set
 *  - hexera-spent and hexera-ledger HCS topics (only the operator can submit)
 *  - two merchant accounts and two demo user accounts, funded with the token
 *
 * Writes everything to data/testnet.env. That file holds private keys: keep it out of git.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
if (existsSync(".env")) process.loadEnvFile(".env");
import {
  AccountCreateTransaction,
  AccountId,
  Client,
  Hbar,
  KeyList,
  PrivateKey,
  TokenCreateTransaction,
  TokenSupplyType,
  TokenType,
  TopicCreateTransaction,
  TransferTransaction,
  TokenId,
} from "@hiero-ledger/sdk";
import { parsePrivateKey } from "@hexera/hedera";

const opId = process.env.HEDERA_OPERATOR_ID;
const opKeyStr = process.env.HEDERA_OPERATOR_KEY;
if (!opId || !opKeyStr) {
  console.error("Set HEDERA_OPERATOR_ID and HEDERA_OPERATOR_KEY (a funded testnet account from portal.hedera.com) in .env");
  process.exit(1);
}
const opKey = parsePrivateKey(opKeyStr);
const client = Client.forTestnet().setOperator(AccountId.fromString(opId), opKey);
const hashscan = (kind: string, id: string) => `https://hashscan.io/testnet/${kind}/${id}`;

async function account(key: PrivateKey | KeyList, hbar: number, memo: string) {
  const tx = await new AccountCreateTransaction()
    .setKeyWithoutAlias(key)
    .setInitialBalance(new Hbar(hbar))
    .setMaxAutomaticTokenAssociations(10)
    .setAccountMemo(memo)
    .execute(client);
  const id = (await tx.getReceipt(client)).accountId!.toString();
  console.log(`  ${memo}: ${id}  ${hashscan("account", id)}`);
  return id;
}

async function topic(memo: string) {
  const tx = await new TopicCreateTransaction().setTopicMemo(memo).setSubmitKey(opKey.publicKey).setAdminKey(opKey.publicKey).execute(client);
  const id = (await tx.getReceipt(client)).topicId!.toString();
  console.log(`  ${memo}: ${id}  ${hashscan("topic", id)}`);
  return id;
}

console.log("Creating Hexera testnet resources…");

// 1. Threshold-key treasury (2 of 3). The facilitator holds keys 1 and 2 for the demo;
//    in production key 2 lives with a separate operator (or signs a ScheduleCreate).
const tKeys = [PrivateKey.generateECDSA(), PrivateKey.generateECDSA(), PrivateKey.generateECDSA()];
const treasuryKeyList = new KeyList(tKeys.map((k) => k.publicKey), 2);
const treasury = await account(treasuryKeyList, 5, "hexera-treasury (2-of-3)");

// 2. Token
let tokenId = process.env.HEXERA_TOKEN_ID;
let ownToken = false;
if (!tokenId) {
  const tx = await new TokenCreateTransaction()
    .setTokenName("Hexera Test USD")
    .setTokenSymbol("hUSD")
    .setDecimals(6)
    .setInitialSupply(1_000_000_000_000) // 1M hUSD
    .setTreasuryAccountId(opId)
    .setTokenType(TokenType.FungibleCommon)
    .setSupplyType(TokenSupplyType.Infinite)
    .setSupplyKey(opKey.publicKey)
    .execute(client);
  tokenId = (await tx.getReceipt(client)).tokenId!.toString();
  ownToken = true;
  console.log(`  test stablecoin hUSD: ${tokenId}  ${hashscan("token", tokenId)}`);
} else {
  console.log(`  using existing token ${tokenId}`);
}

// 3. Topics
const spentTopic = await topic("hexera-spent");
const ledgerTopic = await topic("hexera-ledger");

// 4. Merchants and demo users
const merchantA = await account(PrivateKey.generateECDSA(), 1, "merchant daily-ledger");
const merchantB = await account(PrivateKey.generateECDSA(), 1, "merchant quant-feed");
const users: { id: string; key: PrivateKey }[] = [];
for (const name of ["user-1", "user-2"]) {
  const key = PrivateKey.generateECDSA();
  users.push({ id: await account(key, 5, `demo ${name}`), key });
}

if (ownToken) {
  let tx = new TransferTransaction();
  for (const u of users) tx = tx.addTokenTransfer(TokenId.fromString(tokenId), opId, -25_000_000).addTokenTransfer(TokenId.fromString(tokenId), u.id, 25_000_000);
  await (await tx.execute(client)).getReceipt(client);
  console.log("  funded demo users with 25 hUSD each");
} else {
  console.log(`  fund the demo users with ${tokenId} yourself (e.g. the Circle testnet faucet)`);
}

const env = `# Generated by scripts/setup-testnet.ts on ${new Date().toISOString()} — contains private keys
HEXERA_MODE=testnet
HEDERA_NETWORK=testnet
HEDERA_OPERATOR_ID=${opId}
HEDERA_OPERATOR_KEY=${opKeyStr}
HEXERA_TREASURY_ID=${treasury}
# 2 of the 3 treasury keys (the third is printed below as the offline recovery key)
HEXERA_TREASURY_KEYS=${tKeys[0].toStringDer()},${tKeys[1].toStringDer()}
HEXERA_TOKEN_ID=${tokenId}
HEXERA_SPENT_TOPIC_ID=${spentTopic}
HEXERA_LEDGER_TOPIC_ID=${ledgerTopic}
HEXERA_MERCHANTS=daily-ledger:${merchantA}:The Daily Ledger,quant-feed:${merchantB}:Quant Feed
DEMO_USER_1_ID=${users[0].id}
DEMO_USER_1_KEY=${users[0].key.toStringDer()}
DEMO_USER_2_ID=${users[1].id}
DEMO_USER_2_KEY=${users[1].key.toStringDer()}
# Offline recovery key (key 3 of the treasury KeyList). Move it somewhere safe.
# HEXERA_TREASURY_KEY_3=${tKeys[2].toStringDer()}
`;
mkdirSync("data", { recursive: true });
writeFileSync("data/testnet.env", env, { mode: 0o600 });
console.log("\nWrote data/testnet.env. Merge it into .env (keep the World ID settings you already have), then run: npm run dev");
client.close();
